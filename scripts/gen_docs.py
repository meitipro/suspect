#!/usr/bin/env python3
"""
Generate the docs pages and site data that are copies of the contract and its records.

    python scripts/gen_docs.py           # write the files
    python scripts/gen_docs.py --check   # exit 1 if any file differs from what would be written

A method cannot exist in the code and be missing from the docs, and the judge
prompt on the site cannot drift from the one validators read, because both are
written from contracts/suspect.py by this script, and a test runs --check.

Writes:
  web/content/docs/reference/contract.mdx    every public method, from the source
  web/content/docs/reference/errors.mdx      every refusal sentence, from the source
  web/content/docs/reference/addresses.mdx   the deployment, from contracts/FROZEN.json
  web/content/docs/more/judge-prompt.mdx     the judge prompt, word for word
  web/content/docs/more/evaluation.mdx       the golden run, from eval/results.json
  web/content/docs/quickstart.mdx            the sample code, from web/examples/quickstart.mjs
  web/content/docs/name-a-suspect.mdx        the read samples, from web/examples/
  web/lib/contract.generated.json            limits and the prompt, for the site
"""

from __future__ import annotations

import ast
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "suspect.py"
DOCS = ROOT / "web" / "content" / "docs"
EXAMPLES = ROOT / "web" / "examples"
REPO = "https://github.com/meitipro/suspect/blob/main"

HEADER = "{/* Generated by scripts/gen_docs.py from contracts/suspect.py. Do not edit by hand. */}\n\n"


def load():
    source = CONTRACT.read_text(encoding="utf-8")
    return source, ast.parse(source)


def constant(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and ast.unparse(node.targets[0]) == name:
            try:
                return ast.literal_eval(node.value)
            except ValueError:
                return ast.unparse(node.value)
    raise KeyError(name)


def contract_class(tree: ast.Module) -> ast.ClassDef:
    return next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Suspect")


def kind_of(node: ast.FunctionDef) -> str:
    for deco in node.decorator_list:
        text = ast.unparse(deco)
        if text == "gl.public.write":
            return "write"
        if text == "gl.public.write.payable":
            return "payable"
        if text == "gl.public.view":
            return "view"
    return ""


def mdx_text(text: str) -> str:
    """Plain prose into MDX: braces and angle brackets would be read as code."""
    return text.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace(">", "&gt;")


def signature(node: ast.FunctionDef) -> str:
    args = ", ".join(f"{a.arg}: {ast.unparse(a.annotation)}" for a in node.args.args[1:])
    returns = ast.unparse(node.returns) if node.returns else "None"
    return f"{node.name}({args}) -> {returns}"


def methods(tree: ast.Module) -> list[dict]:
    out = []
    for node in contract_class(tree).body:
        if isinstance(node, ast.FunctionDef) and kind_of(node):
            doc = ast.get_docstring(node) or ""
            out.append(
                {
                    "name": node.name,
                    "kind": kind_of(node),
                    "signature": signature(node),
                    "args": [{"name": a.arg, "type": ast.unparse(a.annotation)} for a in node.args.args[1:]],
                    "returns": ast.unparse(node.returns) if node.returns else "None",
                    "doc": " ".join(doc.split()),
                    "line": node.lineno,
                }
            )
    return out


def refusals(tree: ast.Module) -> list[dict]:
    """Every UserError sentence, with the function it can come from. Dynamic parts read as '…'."""

    def text_of(expr: ast.AST) -> tuple[str, str]:
        parts: list[str] = []

        def walk(e: ast.AST) -> None:
            if isinstance(e, ast.BinOp) and isinstance(e.op, ast.Add):
                walk(e.left)
                walk(e.right)
            elif isinstance(e, ast.Constant) and isinstance(e.value, str):
                parts.append(e.value)
            elif isinstance(e, ast.Name) and e.id in ("E", "L"):
                parts.append("\x00" + e.id)
            else:
                parts.append("…")

        walk(expr)
        prefix = parts[0][1:] if parts and parts[0].startswith("\x00") else ""
        body = "".join(p for p in parts if not p.startswith("\x00"))
        return prefix, body

    owner: dict[int, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            for inner in ast.walk(node):
                if hasattr(inner, "lineno"):
                    owner.setdefault(inner.lineno, node.name)
    rows: dict[tuple, dict] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and ast.unparse(node.func) == "gl.vm.UserError" and node.args:
            prefix, body = text_of(node.args[0])
            key = (prefix, body)
            where = owner.get(node.lineno, "")
            row = rows.setdefault(key, {"prefix": prefix, "text": body, "where": []})
            if where and where not in row["where"]:
                row["where"].append(where)
    return sorted(rows.values(), key=lambda r: (r["prefix"], r["text"]))


def limits(tree: ast.Module) -> dict:
    out = {}
    for name in ("MAX_TITLE", "MAX_TEXT", "MAX_OBSERVATIONS", "MAX_HYPOTHESES", "MAX_PER_AUTHOR", "WINDOW_DAYS"):
        out[name] = constant(tree, name)
    out["PIN_FEE_GEN"] = 1
    out["MIN_BOND_GEN"] = 3
    return out


def frozen() -> dict:
    path = ROOT / "contracts" / "FROZEN.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))["deployments"].get("studio-next", {})


def front(title: str, description: str) -> str:
    return f"---\ntitle: {json.dumps(title)}\ndescription: {json.dumps(description)}\n---\n\n"


def fence(lang: str, body: str, title: str = "") -> str:
    header = f"```{lang}" + (f' title="{title}"' if title else "")
    return f"{header}\n{body.rstrip()}\n```\n"


def step_of(example: pathlib.Path, step: str) -> str:
    """The code between '// --- step: name' and the next marker, comments kept."""
    text = example.read_text(encoding="utf-8")
    marks = [m for m in re.finditer(r"^// --- step: (\w+)\n", text, re.M)]
    for i, m in enumerate(marks):
        if m.group(1) == step:
            end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            return text[m.end() : end].strip("\n")
    raise KeyError(step)


# --- pages ------------------------------------------------------------------


def page_contract(tree: ast.Module) -> str:
    rows = methods(tree)
    refs = refusals(tree)
    out = [front("Contract reference", "All ten methods of the Suspect contract, generated from the source."), HEADER]
    out.append(
        "One contract, ten methods. Seven write, three read. Money moves only in `withdraw`: `add_observation` and `propose` take deposits and bonds in, "
        "and `check`, `resolve` and `lock_board` only move balances inside the contract.\n\n"
    )
    out.append("| Method | Kind | What it does |\n|---|---|---|\n")
    for m in rows:
        kind = {"write": "write", "payable": "write, payable", "view": "view"}[m["kind"]]
        summary = mdx_text(m["doc"].split(". ")[0].rstrip(".") + ".")
        out.append(f"| [`{m['name']}`](#{m['name'].replace('_', '-')}) | {kind} | {summary} |\n")
    out.append("\n")
    for m in rows:
        out.append(f"## {m['name']}\n\n")
        out.append(fence("python", m["signature"]))
        out.append(f"\n{mdx_text(m['doc'])}\n\n")
        mine = [r for r in refs if m["name"] in r["where"] and r["prefix"] == "E"]
        if mine:
            out.append("Refuses with:\n\n")
            for r in mine:
                out.append(f"- {mdx_text(r['text'])}\n")
            out.append("\n")
    out.append(
        f"The source is [`contracts/suspect.py`]({REPO}/contracts/suspect.py). `get_board` takes a board id, an account address (its balance, boards, hypotheses and clues) or an empty string (the totals and the newest boards); `list_hypotheses` takes a board id, or 0 for the newest across every board. "
        "Every view answers `{\"found\": false}` for an unknown id instead of raising, and always carries `totals`.\n"
    )
    return "".join(out)


def page_errors(tree: ast.Module) -> str:
    refs = refusals(tree)
    out = [front("Errors", "Every sentence the contract refuses with, generated from the source."), HEADER]
    out.append(
        "A refusal is a deterministic `UserError` whose sentence starts with `[EXPECTED]`. Validators agree on it byte for byte, so the transaction is "
        "**ACCEPTED** with an execution error. The site and the scripts treat that as a refusal, never as success: success is an accepted status "
        "**and** a leader execution that returned.\n\n"
    )
    out.append(
        "A model answer that cannot be read is `[LLM_ERROR]`. It always disagrees, so the round rotates to a committee that can answer; "
        "nothing is settled by it.\n\n"
    )
    out.append("| Sentence | From |\n|---|---|\n")
    for r in refs:
        if r["prefix"] == "E":
            where = ", ".join(f"`{w}`" for w in r["where"] if not w.startswith("_")) or ", ".join(f"`{w}`" for w in r["where"])
            out.append(f"| {mdx_text(r['text'])} | {where} |\n")
    out.append("\n## Unreadable model answers\n\n| Sentence | From |\n|---|---|\n")
    for r in refs:
        if r["prefix"] == "L":
            out.append(f"| `[LLM_ERROR]` {mdx_text(r['text'])} | {', '.join(f'`{w}`' for w in r['where'])} |\n")
    return "".join(out)


